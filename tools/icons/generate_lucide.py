"""Generate bounded Compose path data from the pinned official lucide-static archive.

Usage: python tools/icons/generate_lucide.py path/to/lucide-static-0.456.0.tgz
No extraction, downloads, SVG interpreter, or npm execution is needed at build/runtime.
"""
import base64
import hashlib
import json
from pathlib import Path
import re
import sys
import tarfile
import xml.etree.ElementTree as ET

VERSION = "0.456.0"
INTEGRITY = "OBAf4Vka0Y6L57vcCVOAR7mQgdOr0oIk5LKlLc06OX2N4wD5GKL0BAmDOdBE2jPIjv3JbICxObw1A3seKx/0BA=="
ROOT = Path(__file__).resolve().parents[2]


def number(value):
    result = float(value)
    assert -1000 <= result <= 1000
    return f"{result:g}"


def shape_path(element):
    tag = element.tag.split("}")[-1]
    a = element.attrib
    allowed = {
        "path": {"d"}, "circle": {"cx", "cy", "r", "fill"},
        "ellipse": {"cx", "cy", "rx", "ry"}, "line": {"x1", "y1", "x2", "y2"},
        "rect": {"x", "y", "width", "height", "rx", "ry"},
        "polygon": {"points"}, "polyline": {"points"},
    }
    assert tag in allowed and a.keys() <= allowed[tag]
    n = lambda key, default="0": float(a.get(key, default))
    if tag == "path":
        path = re.sub(r"\s+", " ", a["d"]).strip()
    elif tag in ("circle", "ellipse"):
        x, y = n("cx"), n("cy")
        rx = n("r") if tag == "circle" else n("rx")
        ry = n("r") if tag == "circle" else n("ry")
        path = f"M{x-rx:g} {y:g}a{rx:g} {ry:g} 0 1 0 {2*rx:g} 0a{rx:g} {ry:g} 0 1 0 {-2*rx:g} 0Z"
    elif tag == "rect":
        x, y, w, h = n("x"), n("y"), n("width"), n("height")
        rx = min(n("rx", a.get("ry", "0")), w / 2)
        ry = min(n("ry", a.get("rx", "0")), h / 2)
        if rx > 0 and ry > 0:
            path = (f"M{x+rx:g} {y:g}H{x+w-rx:g}A{rx:g} {ry:g} 0 0 1 {x+w:g} {y+ry:g}"
                    f"V{y+h-ry:g}A{rx:g} {ry:g} 0 0 1 {x+w-rx:g} {y+h:g}"
                    f"H{x+rx:g}A{rx:g} {ry:g} 0 0 1 {x:g} {y+h-ry:g}"
                    f"V{y+ry:g}A{rx:g} {ry:g} 0 0 1 {x+rx:g} {y:g}Z")
        else:
            path = f"M{x:g} {y:g}h{w:g}v{h:g}h{-w:g}Z"
    elif tag == "line":
        path = f"M{number(a['x1'])} {number(a['y1'])}L{number(a['x2'])} {number(a['y2'])}"
    else:
        points = re.split(r"[\s,]+", a["points"].strip())
        assert len(points) >= 4 and len(points) % 2 == 0
        path = "M" + " ".join(number(v) for v in points[:2])
        path += "L" + " ".join(number(v) for v in points[2:])
        if tag == "polygon":
            path += "Z"
    assert re.fullmatch(r"[MmZzLlHhVvCcSsQqTtAa0-9eE.,+\- ]+", path)
    assert a.get("fill", "none") in ("none", "currentColor")
    return path, a.get("fill") == "currentColor"


def main(archive):
    data = Path(archive).read_bytes()
    assert base64.b64encode(hashlib.sha512(data).digest()).decode() == INTEGRITY, "Archive integrity mismatch"
    lines = []
    with tarfile.open(archive) as source:
        tags = json.load(source.extractfile("package/tags.json"))
        for member in sorted(source.getnames()):
            if not member.startswith("package/icons/") or not member.endswith(".svg"):
                continue
            name = Path(member).stem
            assert re.fullmatch(r"[a-z0-9-]+", name) and len("lucide:" + name) <= 64
            svg = ET.fromstring(source.extractfile(member).read())
            for key, value in {"viewBox": "0 0 24 24", "fill": "none", "stroke": "currentColor",
                               "stroke-width": "2", "stroke-linecap": "round", "stroke-linejoin": "round"}.items():
                assert svg.attrib[key] == value, (member, key)
            strokes, fills = [], []
            for element in svg:
                path, filled = shape_path(element)
                (fills if filled else strokes).append(path)
            words = " ".join(sorted(set(re.findall(r"[a-z0-9]+", " ".join(tags.get(name, [])).lower()))))
            # Keep each element separate: an SVG path may start with relative `m`,
            # which starts at the origin rather than the previous element's endpoint.
            lines.append("\t".join([name, "|".join(strokes), "|".join(fills), words]))
        license_text = source.extractfile("package/LICENSE").read()
    # Keep each JVM string well below the 65535-byte constant-pool limit.
    chunks, current = [], ""
    for line in lines:
        if len(current.encode()) + len(line.encode()) > 24000:
            chunks.append(current)
            current = ""
        current += line + "\n"
    if current:
        chunks.append(current)
    output = (
        "// Generated by tools/icons/generate_lucide.py; do not edit.\n"
        "// Lucide 0.456.0 (ISC, with Feather MIT portions). See assets/licenses/lucide-0.456.0.txt.\n"
        "package com.ai.assistance.operit.ui.common.icons\n\n"
        "internal object LucideIconData {\n"
        f'    const val VERSION = "{VERSION}"\n'
        f"    const val COUNT = {len(lines)}\n"
        "    val entries: Map<String, String> by lazy {\n"
        "        listOf(" + ", ".join(f"chunk{i}()" for i in range(len(chunks))) + ")\n"
        "            .flatMap { it.lineSequence().filter(String::isNotBlank).toList() }\n"
        "            .associate { it.substringBefore('\\t') to it.substringAfter('\\t') }\n"
        "    }\n"
    )
    for i, chunk in enumerate(chunks):
        output += f'    private fun chunk{i}(): String = """\n{chunk}"""\n'
    output += "}\n"
    dest = ROOT / "app/src/main/java/com/ai/assistance/operit/ui/common/icons/LucideIconData.kt"
    dest.write_text(output, encoding="utf-8", newline="\n")
    license_file = ROOT / "app/src/main/assets/licenses/lucide-0.456.0.txt"
    license_file.parent.mkdir(parents=True, exist_ok=True)
    license_file.write_bytes(license_text)
    print(f"Generated {len(lines)} icons in {len(chunks)} chunks; source {dest.stat().st_size} bytes.")


if __name__ == "__main__":
    main(sys.argv[1])
