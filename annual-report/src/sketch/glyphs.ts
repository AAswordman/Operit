// 坐标系：y 从 0 到 100 为字身高度，100 为基线，下伸部分可到 135；x 从 0 到 advance。
// 每个笔画是按书写顺序排列的控制点，渲染时串成平滑曲线，并按笔画顺序做描写动画。
// 本文件不能有任何 import：入口徽章的生成脚本在 Node 中直接加载它。

export type StrokePoint = [number, number];

export interface Glyph {
  advance: number;
  /** 汉字不做斜体处理。 */
  upright?: boolean;
  strokes: StrokePoint[][];
}

const dot = (x: number, y: number, r = 3): StrokePoint[] => [
  [x, y - r],
  [x + r, y],
  [x, y + r],
  [x - r, y],
  [x, y - r],
];

